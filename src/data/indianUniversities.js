export function formatUniversityLabel(uni) {
  if (!uni) return ''
  if (typeof uni === 'string') return uni
  return `${uni.name} (${uni.city}, ${uni.state})`
}

export function searchUniversities(query, limit = 50) {
  if (!query || typeof query !== 'string') return INDIAN_UNIVERSITIES.slice(0, limit)
  const q = query.trim().toLowerCase()
  const tokens = q.split(/\s+/).filter(Boolean)

  const matches = []
  for (const item of INDIAN_UNIVERSITIES) {
    const nameLower = item.name.toLowerCase()
    const shortLower = item.shortName.toLowerCase()
    const cityLower = item.city.toLowerCase()
    const stateLower = item.state.toLowerCase()

    // Match if all search tokens are found in name, shortName, city, or state
    const matchesAllTokens = tokens.every((token) =>
      nameLower.includes(token) ||
      shortLower.includes(token) ||
      cityLower.includes(token) ||
      stateLower.includes(token)
    )

    if (matchesAllTokens) {
      matches.push(item)
      if (matches.length >= limit) break
    }
  }

  return matches
}

export default INDIAN_UNIVERSITIES
